import dotenv from 'dotenv';
import pg from 'pg';
import sharp from 'sharp';
import { jsPDF } from 'jspdf';
import { randomUUID, createHash } from 'node:crypto';
import { mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';

if (process.env.SCHEMATICS_QA_LOCAL !== '1') throw new Error('Prueba opt-in: SCHEMATICS_QA_LOCAL=1 node scripts/test-schematics-ocr.mjs');
dotenv.config({ quiet: true });
const database = new URL(process.env.DATABASE_URL);
assert.equal(database.hostname, 'localhost'); assert.equal(database.port, '5434');
const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL, max: 1 });
const tag = 'schematics-ocr-qa-' + randomUUID();
const root = path.resolve(process.env.SCHEMATICS_ROOT ?? 'upload/schematics');
const relativePath = `${tag}/fixture.pdf`;
const id = createHash('sha256').update(relativePath).digest('hex');
const userId = tag + '-tech';
const adminId = tag + '-admin';
try {
  const image = await sharp(Buffer.from('<svg width="1400" height="400"><rect width="100%" height="100%" fill="white"/><text x="80" y="180" font-size="72" font-family="Arial" fill="black">U4000 VBAT TEST POINT</text></svg>')).png().toBuffer();
  const doc = new jsPDF({ orientation: 'landscape', unit: 'pt', format: [1400, 400] });
  doc.addImage(image, 'PNG', 0, 0, 1400, 400);
  const bytes = Buffer.from(doc.output('arraybuffer'));
  const sha256 = createHash('sha256').update(bytes).digest('hex');
  const asset = { id, name: 'fixture.pdf', kind: 'pdf', brand: 'QA', model: tag, modelKey: tag, relativePath, size: bytes.length, sha256, status: 'ready' };
  await mkdir(path.join(root, tag), { recursive: true });
  await writeFile(path.join(root, relativePath), bytes);
  await pool.query('INSERT INTO users(id,email,password,name,role,"updatedAt") VALUES($1,$2,$3,$4,\'TECHNICIAN\',now())', [userId, `${tag}@example.invalid`, 'invalid-hash', 'QA OCR']);
  await pool.query('INSERT INTO users(id,email,password,name,role,"updatedAt") VALUES($1,$2,$3,$4,\'ADMIN\',now())', [adminId, `${adminId}@example.invalid`, 'invalid-hash', 'QA identidad']);
  await pool.query('INSERT INTO schematics.assets(id,relative_path,sha256,kind,model_key,metadata) VALUES($1,$2,$3,$4,$5,$6)', [id, relativePath, sha256, 'pdf', tag, JSON.stringify(asset)]);
  const headers = { Cookie: `session_user_id=${userId}; session_role=TECHNICIAN`, 'Content-Type': 'application/json' };
  const identityEndpoint = `http://localhost:3000/api/schematics/${id}/identity`;
  const identity = { verified: true, brand: 'QA', model: tag, boardCode: 'QA-BOARD', revision: '1', aliases: ['QA alias'] };
  const forbidden = await fetch(identityEndpoint, { method: 'POST', headers, body: JSON.stringify(identity) }); assert.equal(forbidden.status, 403);
  const adminHeaders = { ...headers, Cookie: `session_user_id=${adminId}; session_role=ADMIN` };
  const invalidIdentity = await fetch(identityEndpoint, { method: 'POST', headers: adminHeaders, body: JSON.stringify({ ...identity, brand: true }) }); assert.equal(invalidIdentity.status, 400);
  const verified = await fetch(identityEndpoint, { method: 'POST', headers: adminHeaders, body: JSON.stringify(identity) }); assert.equal(verified.status, 200);
  const updated = await verified.json(); assert.equal(updated.asset.identityVerifiedBy, adminId);
  const updates = await Promise.all(['2','3'].map(revision => fetch(identityEndpoint, { method: 'POST', headers: adminHeaders, body: JSON.stringify({ ...identity, revision }) })));
  assert.ok(updates.every(response => [200,409].includes(response.status)));
  const persisted = (await pool.query('SELECT metadata FROM schematics.assets WHERE id=$1', [id])).rows[0].metadata;
  assert.equal(persisted.identityVerificationHistory.length, updates.filter(response => response.status === 200).length);
  const response = await fetch(`http://localhost:3000/api/schematics/${id}/ocr`, { method: 'POST', headers, body: JSON.stringify({ pages: [1] }) });
  const result = await response.json();
  assert.equal(response.status, 200, JSON.stringify(result));
  assert.equal(result.source, 'ocr'); assert.ok(result.pages[0].characters > 10);
  const search = await fetch(`http://localhost:3000/api/schematics/${id}/references?q=U4000`, { headers });
  const reference = await search.json(); assert.equal(search.status, 200, JSON.stringify(reference)); assert.equal(reference.matches[0].page, 1); assert.ok(reference.sources.includes('ocr'));
  const stored = (await pool.query('SELECT content,asset_sha256,content_sha256 FROM schematics.pages WHERE asset_id=$1', [id])).rows[0];
  assert.ok(stored.content.includes('U4000')); assert.equal(stored.asset_sha256, sha256); assert.ok(stored.content_sha256);
  assert.equal(createHash('sha256').update(await readFile(path.join(root, relativePath))).digest('hex'), sha256);
  const invalid = await fetch(`http://localhost:3000/api/schematics/${id}/ocr`, { method: 'POST', headers, body: JSON.stringify({ pages: [2] }) }); assert.equal(invalid.status, 400);
  process.stdout.write(`PASS: scanned fixture OCR -> index -> reference page 1; original preserved; out-of-range rejected; languages=${result.languages}\n`);
} finally {
  await pool.query('DELETE FROM schematics.assets WHERE id=$1', [id]);
  await pool.query('DELETE FROM users WHERE id=ANY($1::text[])', [[userId, adminId]]);
  await pool.end();
  await rm(path.join(root, tag), { recursive: true, force: true });
  await rm(path.join(root, '.index', `${id}.json`), { force: true });
}
